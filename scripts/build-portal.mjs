import { build } from "esbuild";
import { format } from "prettier";
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const root = new URL("../", import.meta.url);
const directory = new URL("client/platform/generated/", root);
const result = await build({
  stdin: {
    contents: 'export { createPortal } from "react-dom";',
    resolveDir: fileURLToPath(root),
  },
  bundle: true,
  platform: "browser",
  format: "esm",
  target: "es2020",
  define: { "process.env.NODE_ENV": '"production"' },
  external: ["react"],
  write: false,
  banner: {
    js: "// Generated by npm run build:portal. React DOM 19.1.0 (MIT). See react-dom.LICENSE.",
  },
});
const code = await format(result.outputFiles[0].text, { parser: "babel" });
if (/\bprocess\b/.test(code))
  throw new Error("Portal artifact must not depend on Node globals");
const files = new Map([
  ["react-dom-portal.js", code],
  [
    "react-dom-portal.d.ts",
    await format(
      'import type { ReactNode, ReactPortal } from "react";\nexport function createPortal(children: ReactNode, container: object): ReactPortal;\n',
      { parser: "typescript" },
    ),
  ],
  [
    "react-dom.LICENSE",
    await readFile(new URL("node_modules/react-dom/LICENSE", root), "utf8"),
  ],
]);
if (process.argv.includes("--check")) {
  for (const [name, content] of files) {
    if ((await readFile(new URL(name, directory), "utf8")) !== content)
      throw new Error(
        `Stale portal artifact: ${name}. Run npm run build:portal`,
      );
  }
  console.log("Portal artifact is current and browser-safe");
} else {
  await mkdir(directory, { recursive: true });
  for (const [name, content] of files)
    await writeFile(new URL(name, directory), content);
}
